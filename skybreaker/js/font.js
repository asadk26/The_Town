  const CELL_H = 9;
  const keys = Object.keys(G);
  const meta = {};
  let atlasW = 0;
  for (const k of keys) {
    const w = G[k][0].length;
    meta[k] = { x: atlasW, w };
    atlasW += w + 1;
  }
  const atlas = document.createElement('canvas');
  atlas.width = atlasW;
  atlas.height = CELL_H;
  const actx = atlas.getContext('2d');
  actx.fillStyle = '#fff';
  for (const k of keys) {
    const rows = G[k];
    for (let y = 0; y < rows.length; y++)
      for (let x = 0; x < rows[y].length; x++)
        if (rows[y][x] === '#') actx.fillRect(meta[k].x + x, y, 1, 1);
  }

  const tinted = {};
  function sheet(color) {
    if (tinted[color]) return tinted[color];
    const c = document.createElement('canvas');
    c.width = atlas.width; c.height = atlas.height;
    const x = c.getContext('2d');
    x.drawImage(atlas, 0, 0);
    x.globalCompositeOperation = 'source-in';
    x.fillStyle = color;
    x.fillRect(0, 0, c.width, c.height);
    return (tinted[color] = c);
  }

  function width(str) {
    let w = 0;
    for (const ch of str) {
      const m = meta[ch] || meta['?'];
      w += m.w + 1;
    }
    return Math.max(0, w - 1);
  }

  /* draw(ctx, text, x, y, color, opts) — opts.shadow (colour or false),
     opts.align 'left' | 'center' | 'right', opts.scale (whole number). */
  function draw(ctx, str, x, y, color = '#fff', opts = {}) {
    str = String(str);
    const scale = opts.scale || 1;
    const w = width(str) * scale;
    if (opts.align === 'center') x -= Math.floor(w / 2);
    else if (opts.align === 'right') x -= w;
    x = Math.round(x); y = Math.round(y);
    const shadow = opts.shadow === undefined ? '#1a1028' : opts.shadow;
    if (shadow) run(ctx, str, x + scale, y + scale, sheet(shadow), scale);
    run(ctx, str, x, y, sheet(color), scale);
    return w;
  }

  function run(ctx, str, x, y, src, scale) {
    for (const ch of str) {
      const m = meta[ch] || meta['?'];
      ctx.drawImage(src, m.x, 0, m.w, CELL_H, x, y, m.w * scale, CELL_H * scale);
      x += (m.w + 1) * scale;
    }
  }

  /* Greedy word wrap to a pixel width; honours explicit \n. */
  function wrap(str, maxW) {
    const out = [];
    for (const para of String(str).split('\n')) {
      let line = '';
      for (const word of para.split(' ')) {
        const tryLine = line ? line + ' ' + word : word;
        if (width(tryLine) <= maxW || !line) line = tryLine;
        else { out.push(line); line = word; }
      }
      out.push(line);
    }
    return out;
  }

  return { draw, width, wrap, LINE: 10 };
